def test_render_report_md_stable_order_no_placeholder_text() -> None:
    payload = _minimal_report_payload()
    payload["report_summary_index"] = [
        {
            "section_name": "Named entities",
            "descriptor": "Entities",
            "source_modules": ["ner"],
        },
        {
            "section_name": "Sentiment",
            "descriptor": "Tone",
            "source_modules": ["sentiment"],
        },
    ]
    payload["modules"] = {
        "ner": {
            "module_status": "ran",
            "report_contribution_status": "full_section",
            "section_payload": {"entities": [{"text": "Alice", "label": "PERSON"}]},
        },
        "sentiment": {
            "module_status": "ran",
            "report_contribution_status": "full_section",
            "section_payload": {"mean_compound": 0.1},
        },
    }
    md = render_report_md(payload)
    # Sentiment comes before ner in SECTION_ORDER, so Sentiment section should appear before Named entities
    pos_sentiment = md.find("## Sentiment")
    pos_ner = md.find("## Named entities")
    assert pos_sentiment != -1
    assert pos_ner != -1
    assert pos_sentiment < pos_ner
    assert "No data available" not in md


