def test_md_to_txt_empty() -> None:
    assert md_to_txt("") == ""
    assert md_to_txt("   ") == "\n"


def test_md_to_txt_headers_converted() -> None:
    md = "# Title\n\nBody"
    txt = md_to_txt(md)
    assert "Title" in txt
    assert "=" in txt
    assert "#" not in txt or "Title" in txt
    md2 = "## Section 2\n\nContent"
    txt2 = md_to_txt(md2)
    assert "Section 2" in txt2
    assert "-" in txt2


def test_md_to_txt_bold_stripped() -> None:
    md = "Hello **world** and __again__."
    txt = md_to_txt(md)
    assert "world" in txt
    assert "again" in txt
    assert "**" not in txt
    assert "__" not in txt


def test_md_to_txt_normalizes_newlines() -> None:
    md = "Line 1\n\n\n\n\nLine 2"
    txt = md_to_txt(md)
    assert "\n\n\n" not in txt
    assert "Line 1" in txt
    assert "Line 2" in txt


def test_md_to_txt_roundtrip_preserves_content() -> None:
    payload = _minimal_report_payload()
    payload["speakers"] = [
        {
            "name": "A",
            "words": 10,
            "pct_total_words": 1.0,
            "duration_hhmmss": "0:00",
            "words_per_min": 0.0,
        }
    ]
    md = render_report_md(payload)
    txt = md_to_txt(md)
    assert "Report: sample" in txt
    assert "A" in txt
    assert "10" in txt


def test_section_order_constant() -> None:
    assert SECTION_ORDER[0] == "header"
    assert "speakers" in SECTION_ORDER
    assert "footer" in SECTION_ORDER
    assert SECTION_ORDER.index("sentiment") < SECTION_ORDER.index("emotion")
    assert "additional_outputs" in SECTION_ORDER
    assert "warnings" in SECTION_ORDER
